"""Generates src/mods/games.tsv from Thunderstore's ecosystem schema.

The table maps a Steam appid to where the player's mod managers keep that game's profiles:

    appid  r2_folder  community  loader

- r2_folder: r2modman's and Thunderstore Mod Manager's per-game folder (`internalFolderName`);
- community: the Thunderstore community key, which is Gale's per-game folder (its slug);
- loader: the schema's `packageLoader` (`bepinex`, `melonloader`, `recursive-melonloader`, ...).

One row per Steam distribution (`steam` and `steam-direct`) of every r2modman entry, sorted by
appid. The launcher embeds the file (`include_str!`); it is data, not code, so a game added to
Thunderstore needs only this script run again.

    tools/gen-mods-games.py ecosystem.json > src/mods/games.tsv

The schema: https://thunderstore.io/api/experimental/schema/dev/latest/ (save it, then pass the
file; this script never touches the network).
"""

import json
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        schema = json.load(f)
    rows = {}
    for community, game in sorted(schema["games"].items()):
        for entry in game.get("r2modman") or []:
            folder = entry.get("internalFolderName") or ""
            loader = entry.get("packageLoader") or ""
            for dist in entry.get("distributions") or []:
                if dist.get("platform") not in ("steam", "steam-direct"):
                    continue
                appid = str(dist.get("identifier", "")).strip()
                if not appid.isdigit():
                    continue
                for cell in (folder, community, loader):
                    if any(c in cell for c in "\t\r\n") or not cell:
                        raise SystemExit(f"appid {appid}: unusable cell {cell!r}")
                row = (int(appid), folder, community, loader)
                if int(appid) in rows and rows[int(appid)] != row:
                    raise SystemExit(f"appid {appid} has two rows: {rows[int(appid)]} and {row}")
                rows[int(appid)] = row
    out = sys.stdout
    out.write("# Generated by tools/gen-mods-games.py from Thunderstore's ecosystem schema "
              f"(schemaVersion {schema.get('schemaVersion', '?')}). Do not edit by hand.\n")
    out.write("# appid\tr2_folder\tcommunity\tloader\n")
    for appid in sorted(rows):
        _, folder, community, loader = rows[appid]
        out.write(f"{appid}\t{folder}\t{community}\t{loader}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
